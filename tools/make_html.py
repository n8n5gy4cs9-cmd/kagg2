#!/usr/bin/env python3
"""Build HTML/*.html from tools/html_src/*.html fragments (styling: tools/html_style.css).

Each fragment starts with <h1>; <h2>/<h3> get ids, anchors and a sidebar. Edit the fragments, not HTML/.
Usage: python3 tools/make_html.py
"""
import re, pathlib, html

root = pathlib.Path(__file__).resolve().parent.parent
src, out = root / "tools" / "html_src", root / "HTML"
css = (root / "tools" / "html_style.css").read_text()
version = re.search(r'^version = "([^"]+)"', (root / "Cargo.toml").read_text(), re.M).group(1)

PAGES = [  # file, nav label, title
    ("index", "Home", "Kagg2"),
    ("guide", "Player guide", "Player guide"),
    ("manual", "Manual", "Manual"),
    ("developer-guide", "Developer guide", "Developer guide"),
    ("ai-guide", "AI helper guide", "AI helper guide"),
]


def slug(t):
    return re.sub(r"[^a-z0-9]+", "-", re.sub(r"<[^>]+>", "", html.unescape(t)).lower()).strip("-")


def process(body):
    heads = []

    def fix(m):
        lvl, attrs, inner = m.group(1), m.group(2), m.group(3)
        i = slug(inner)
        heads.append((lvl, i, re.sub(r"<[^>]+>", "", inner)))
        return f'<h{lvl} id="{i}">{inner}<a class="a" href="#{i}">#</a></h{lvl}>'

    body = re.sub(r"<h([23])([^>]*)>(.*?)</h\1>", fix, body, flags=re.S)
    return body, heads


def page(name, label, title):
    body = (src / f"{name}.html").read_text()
    nav = "".join(
        f'<a href="{n}.html"{" class=on" if n == name else ""}>{l}</a>' for n, l, _ in PAGES
    )
    head = f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>{title} — Kagg2</title><meta name="description" content="Kagg2: Mars Vikings against the Earth Minions. A bridge-simulator and boarding-FPS campaign.">
<link rel="icon" href="data:image/svg+xml,%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 32 32'%3E%3Cpath fill='%237ff0cf' d='M16 2l5 9h-4v5l6-4v5l-6 4v9h-2v-9l-6-4v-5l6 4v-5h-4z'/%3E%3C/svg%3E">
<style>{css}</style></head><body><header><a class="brand" href="index.html"><span class="rune">ᛟ</span> KAGG2</a><nav aria-label="Main navigation">{nav}</nav><a class="nav-cta" href="guide.html">Start playing <span>ᚠ</span></a></header>"""
    foot = f"""<footer><a class="brand" href="index.html"><span class="rune">ᛟ</span> KAGG2</a><span>MARS VIKINGS AGAINST THE EARTH MINIONS</span><small>v{version} · generated by tools/make_html.py: edit tools/html_src/*.html, not this file</small></footer></body></html>"""
    if name == "index":
        return head + body + foot
    body, heads = process(body)
    side = "".join(f'<a class="l{l}" href="#{i}">{html.escape(t)}</a>' for l, i, t in heads)
    script = """<script>
const links=[...document.querySelectorAll('aside a')];const heads=links.map(a=>document.getElementById(a.getAttribute('href').slice(1)));
const onScroll=()=>{let cur=0,best=-1e9;heads.forEach((h,i)=>{if(!h)return;const t=h.getBoundingClientRect().top;if(t<130&&t>best){best=t;cur=i}});links.forEach((a,i)=>a.classList.toggle('cur',i===cur))};
addEventListener('scroll',onScroll,{passive:true});onScroll();
</script>"""
    return head + f'<div class="wrap"><aside><div class="grp">On this page</div>{side}</aside><main>{body}</main></div>{script}' + foot


out.mkdir(exist_ok=True)
for n, l, t in PAGES:
    (out / f"{n}.html").write_text(page(n, l, t))
    print("wrote", out / f"{n}.html")
