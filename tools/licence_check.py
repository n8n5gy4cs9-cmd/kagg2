#!/usr/bin/env python3
"""Licence audit (T31). Fails (exit 1) when something is wrong; writes LICENCES.md.

Checks: (1) every dependency offers at least one licence compatible with GPL-2.0-or-later,
(2) LICENSE holds the GPL v2 text and Cargo.toml names the licence, (3) no shipped file
(assets/, src/, HTML/, missions/) is byte-identical to a file in REFERENCE_tobe_DELETED/
(generated assets only, see AGENTS.md), (4) every `// ref:` comment is acknowledged in CREDITS.md.
Usage: python3 tools/licence_check.py
"""
import hashlib, json, pathlib, re, subprocess, sys

root = pathlib.Path(__file__).resolve().parent.parent
# Permissive licences that can be combined with GPL-2.0-or-later code (Apache-2.0 is fine
# because "or later" lets the combined work be distributed under GPL-3.0).
OK = {"MIT", "Apache-2.0", "BSD-3-Clause", "BSD-2-Clause", "Zlib", "0BSD", "Unlicense", "ISC", "CC0-1.0"}
problems = []

meta = json.loads(subprocess.check_output(["cargo", "metadata", "--format-version", "1"], cwd=root))
rows = []
for p in sorted(meta["packages"], key=lambda p: (p["name"], p["version"])):
    if p["name"] == "kagg2":
        if p.get("license") != "GPL-2.0-or-later":
            problems.append(f"Cargo.toml license is {p.get('license')!r}, expected GPL-2.0-or-later")
        continue
    expr = (p.get("license") or "").replace("/", " OR ")
    alts = [a.strip(" ()") for a in re.split(r"\s+OR\s+", expr) if a.strip()]
    good = [a for a in alts if a in OK]
    if not good:
        problems.append(f"{p['name']} {p['version']}: licence {expr!r} is not on the allow-list")
    rows.append((p["name"], p["version"], expr or "?", ", ".join(good) or "-"))

lic = root / "LICENSE"
if not lic.exists() or "Version 2, June 1991" not in lic.read_text(errors="ignore"):
    problems.append("LICENSE (GPL v2 text) is missing")

ref = root / "REFERENCE_tobe_DELETED"
if ref.exists():
    def digest(f):
        return hashlib.sha256(f.read_bytes()).hexdigest()
    known = {}
    for f in ref.rglob("*"):
        if f.is_file() and f.stat().st_size > 64:
            known[digest(f)] = f
    for sub in ("assets", "src", "HTML", "missions"):
        for f in (root / sub).rglob("*"):
            if f.is_file() and f.stat().st_size > 64 and digest(f) in known:
                problems.append(f"{f.relative_to(root)} is identical to reference file {known[digest(f)].name}")
else:
    print("note: REFERENCE_tobe_DELETED/ is gone, identical-file check skipped")

credits = (root / "CREDITS.md").read_text()
refs = set()
for f in (root / "src").rglob("*.rs"):
    for m in re.finditer(r"// ref: (\S+)", f.read_text()):
        refs.add(m.group(1))
for r in sorted(refs):
    if not any(w in credits for w in ("Space Nerds", "Quake 2")):
        problems.append("CREDITS.md does not acknowledge the referenced projects")
        break

out = ["# Third-party licences", "",
       "Generated by `python3 tools/licence_check.py` (T31). Kagg2 itself is GPL-2.0-or-later (`LICENSE`).",
       "Every crate below offers a permissive licence (column 4) that can be combined with it.", "",
       "| Crate | Version | Declared licence | Used under |", "|---|---|---|---|"]
out += [f"| {n} | {v} | {e} | {g} |" for n, v, e, g in rows]
(root / "LICENCES.md").write_text("\n".join(out) + "\n")
print(f"{len(rows)} dependencies checked, {len(refs)} `// ref:` comments, LICENCES.md written")
for p in problems:
    print("PROBLEM:", p)
sys.exit(1 if problems else 0)
